"""
backend/services/sample_datasets.py
====================================
Catalog of the built-in onboarding sample datasets.

Purpose: /upload is otherwise a hard gate — no file, no product. These
samples let a brand-new account reach a rendered forecast without owning a
dataset, and they are chosen to land in three different demand quadrants so
the classifier's behaviour is visible rather than asserted.

The CSVs live in backend/static/samples/ and are regenerated by
scripts/generate_sample_datasets.py (dev tooling, never imported at
runtime). They sit under backend/ deliberately: Docker/Dockerfile.backend
already does `COPY backend/ ./backend/`, so they ship in the image with no
Dockerfile change.

SECURITY — the one rule that matters here: `sample_id` arrives from the URL
path and is untrusted. It resolves ONLY by dict lookup in SAMPLE_CATALOG.
The filename that reaches the filesystem always comes from a SampleDataset
we constructed ourselves, so no request-controlled string is ever joined
into a path. Do not "simplify" this into SAMPLES_DIR / f"{sample_id}.csv".
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

# backend/services/ -> backend/ -> backend/static/samples/
SAMPLES_DIR = Path(__file__).resolve().parent.parent / "static" / "samples"


# ── Catalog entry ─────────────────────────────────────────────────────
@dataclass(frozen=True)
class SampleDataset:
    """One built-in dataset.

    `row_count`, `columns` and `demand_class` are declared here rather than
    computed on request so that listing the catalog costs no file I/O. They
    are asserted against the actual CSVs in
    backend/tests/test_sample_datasets.py, so the manifest cannot silently
    drift away from the data it describes.
    """

    id           : str
    title        : str
    description  : str
    demand_class : str
    file_name    : str
    frequency    : str
    row_count    : int
    columns      : tuple[str, ...]


# ── The catalog ───────────────────────────────────────────────────────
# Ordered Smooth -> Intermittent -> Lumpy: easiest to hardest, which is
# also the order the UI presents them in.
SAMPLE_CATALOG: dict[str, SampleDataset] = {
    "retail-daily-smooth": SampleDataset(
        id="retail-daily-smooth",
        title="Retail store sales",
        description=(
            "Two years of daily unit sales for a steady retail line, with "
            "marketing spend and temperature as covariates. Demand every "
            "day and low dispersion — the easy case."
        ),
        demand_class="Smooth",
        file_name="retail-daily-smooth.csv",
        frequency="Daily",
        row_count=730,
        columns=("date", "units_sold", "marketing_spend", "avg_temp_c"),
    ),
    "spare-parts-intermittent": SampleDataset(
        id="spare-parts-intermittent",
        title="Spare parts — intermittent",
        description=(
            "Two years of daily shipments for a slow-moving spare part. "
            "Orders arrive on roughly one day in four, but the order size "
            "is consistent when they do."
        ),
        demand_class="Intermittent",
        file_name="spare-parts-intermittent.csv",
        frequency="Daily",
        row_count=730,
        columns=("date", "units_shipped"),
    ),
    "spare-parts-lumpy": SampleDataset(
        id="spare-parts-lumpy",
        title="Spare parts — lumpy",
        description=(
            "The same shipment pattern, but order size swings wildly when "
            "demand does occur. Sporadic and erratic at once — the quadrant "
            "classical models handle worst."
        ),
        demand_class="Lumpy",
        file_name="spare-parts-lumpy.csv",
        frequency="Daily",
        row_count=730,
        columns=("date", "units_shipped"),
    ),
}


def list_samples() -> list[SampleDataset]:
    """Every catalog entry, in declaration order."""
    return list(SAMPLE_CATALOG.values())


def get_sample(sample_id: str) -> SampleDataset:
    """Resolve an id to its catalog entry. Raises KeyError if unknown."""
    return SAMPLE_CATALOG[sample_id]


def load_sample_bytes(sample_id: str) -> bytes:
    """Read a sample's raw CSV bytes.

    Blocking file I/O — call it through asyncio.to_thread from a route, the
    way upload.py already treats its local-storage write.

    Raises KeyError for an unknown id, before touching the filesystem.
    """
    sample = SAMPLE_CATALOG[sample_id]
    return (SAMPLES_DIR / sample.file_name).read_bytes()
